// Builds work/haftarot.json - the haftara list - from the masora notes in
// work/word_notes.json (the corpus's word-notes table): a note naming a
// haftara ("...הפטרת X") marks its first word, a note "עד כאן" / "עד כן"
// (optionally "לספרדים" / "לאשכנזים") marks a last word.
//
// Usage:  node build-haftarot.mjs
//
// Each start is paired with the first end marker after it in the same book.
// `end.status` says how far to trust that:
//   marked - no other haftara starts in between: this end is its own
//   check  - another haftara starts in between, so the end may belong to that
//            one (e.g. Jer 7:21 Tzav and Jer 8:13 Tisha b'Av both run to 9:23,
//            but Jer 2:4 Masei does not), or the end is for one rite only
//            ("עד כאן לספרדים" - Ezek 36 and 46)
//   none   - no end marker after it in its book (end = null)
// Starts are what the bookmarks need (merge-book.mjs); ends are informational.

import fs from 'node:fs';
import path from 'node:path';
import { WORK, readJson, shortForName, citationKey } from './tanach-lib.mjs';

// ============================================================================
// CONFIG
// ============================================================================
const NOTES_FILE = path.join(WORK, 'word_notes.json');
const OUT_FILE = path.join(WORK, 'haftarot.json');
// A note that starts a haftara: from "הפטרת"/"הפטרה" (and the typo "הפטאה") on.
const START_RE = /הפט[רא][התּ]/;
// A note that ends one, with an optional rite.
const END_RE = /^\s*עד כ(?:א)?ן(?:\s+(ל\S+))?\s*$/;
// ============================================================================

const events = [];
for (const n of readJson(NOTES_FILE).byReason.flatMap((r) => r.notes)) {
  const end = n.note.match(END_RE);
  const startAt = n.note.search(START_RE);
  if (!end && startAt < 0) continue;
  const book = shortForName(n.book);
  const ref = { book, chapter: n.chapter, verse: n.verse, word: n.wordnumber };
  const at = { citation: `${book}${n.chapter}:${n.verse}#${n.wordnumber}`, ktiv: n.wordPlain, ...ref };
  const order = citationKey(ref) * 1000 + n.wordnumber;
  if (end) events.push({ kind: 'end', order, at, rite: end[1] ?? null, note: n.note.trim() });
  else events.push({ kind: 'start', order, at, name: n.note.slice(startAt).trim(), note: n.note.trim(), reasonId: n.reasonId });
}
events.sort((a, b) => a.order - b.order);

const haftarot = [];
events.forEach((e, i) => {
  if (e.kind !== 'start') return;
  const rest = events.slice(i + 1).filter((x) => x.at.book === e.at.book);
  const endIdx = rest.findIndex((x) => x.kind === 'end');
  const end = endIdx < 0 ? null : rest[endIdx];
  // A rite-specific end ("עד כאן לספרדים") may close a different haftara for the other rite.
  const status = !end ? 'none'
    : end.rite || rest.slice(0, endIdx).some((x) => x.kind === 'start') ? 'check' : 'marked';
  const { book, chapter, verse, word, citation, ktiv } = e.at;
  haftarot.push({
    name: e.name,
    start: { citation, book, chapter, verse, word, ktiv },
    end: end ? { citation: end.at.citation, ktiv: end.at.ktiv, rite: end.rite, status } : { status },
    note: e.note,
    ...(e.reasonId !== 13 ? { noteReason: e.reasonId } : {}),
  });
});
const unusedEnds = events.filter((e) => e.kind === 'end' && !haftarot.some((h) => h.end.citation === e.at.citation));

fs.writeFileSync(OUT_FILE, `${JSON.stringify({
  _note: 'Generated by retypeset-test/build-haftarot.mjs from word_notes.json - do not edit; fix the notes and regenerate. end.status: marked = its own end marker; check = another haftara starts before that end, so it may not be this one\'s; none = no end marker.',
  generated: new Date().toISOString(),
  count: haftarot.length,
  haftarot,
}, null, 1)}\n`, 'utf8');

const by = (s) => haftarot.filter((h) => h.end.status === s).length;
console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)}: ${haftarot.length} haftarot (ends: ${by('marked')} marked, ${by('check')} to check, ${by('none')} none)`);
for (const h of haftarot.filter((x) => x.noteReason)) console.log(`  ${h.start.citation} "${h.name}" is filed under note reason ${h.noteReason}, not 13`);
for (const e of unusedEnds) console.log(`  ${e.at.citation} "${e.note}": end marker paired with no start`);
