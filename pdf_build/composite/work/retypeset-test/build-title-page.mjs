// Book title page (front matter, before page 1), laid out after the 1882
// scan's title page (vienna-1882 analysis/0005.png): ספר, the large title,
// the lines about the text and its editor, then the imprint at the foot.
//
// Usage:  node build-title-page.mjs [--no-pdf]
//
// The text comes from title_page.txt (project root), one printed line per
// line; a blank line separates the top block from the imprint, which is set
// at the foot of the page as in the scan. ASCII ' and " become geresh ׳ and
// gershayim ״. Writes title-page.tex and runs xelatex.

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { HERE, WORK } from './tanach-lib.mjs';

// ============================================================================
// Config
// ============================================================================
const TEXT_FILE = path.join(WORK, '..', '..', 'title_page.txt');
// Style of each line, in order, per block: size in pt, space above in mm
// (sizes measured on the scan; the 4th top line, the edition note, is new).
// `fit: true` scales the line to TITLE_WIDTH (the scan's title spans ~0.86 of the text width).
const TOP_STYLES = [
  { size: 32, above: 0 },                 // ספר
  { size: 72, above: 10, fit: true, bold: true }, // תורה נביאים וכתובים
  { size: 34, above: 18 },                // מדויק היטיב על פי המסורה
  { size: 20, above: 16 },                // edition note
  { size: 22, above: 16 },                // הוגה בעיון נמרץ
  { size: 17, above: 14 },                // על ידי
  { size: 21, above: 14 },                // החכם המובהק
  { size: 40, above: 16 },                // the editor's name
];
const BOTTOM_STYLES = [
  { size: 28, above: 0 },                 // place (scan: וויען)
  { size: 38, above: 10 },                // publisher line (scan: בדפוס האדון ...)
  { size: 20, above: 7 },                 // year
  { size: 10, above: 8, english: true },  // font credit (new), small, left to right
];
const TITLE_WIDTH = '0.86\\textwidth';
const FAKE_BOLD = 2.5;                    // the scan's title is a heavy face; Magalith has one weight
const RULE_WIDTH = '1.1in';               // short rule above the imprint (as in the 1872 scan)
const RULE_BELOW = '10mm';
const TOP_SKIP = '22mm';                  // space above ספר
const BOTTOM_SKIP = '6mm';               // space below the year
// ============================================================================

const toHebrewPunct = (s) => s.replace(/"/g, '״').replace(/'/g, '׳');
const lines = fs.readFileSync(TEXT_FILE, 'utf8').replace(/^﻿/, '').split(/\r?\n/).map((l) => l.trim());
while (lines.length && !lines[lines.length - 1]) lines.pop();
const gap = lines.indexOf('');
const top = gap < 0 ? lines : lines.slice(0, gap);
const bottom = gap < 0 ? [] : lines.slice(gap + 1).filter(Boolean);
if (top.length > TOP_STYLES.length || bottom.length > BOTTOM_STYLES.length) {
  throw new Error(`title_page.txt has ${top.length}+${bottom.length} lines; styles cover ${TOP_STYLES.length}+${BOTTOM_STYLES.length}`);
}

// An `english` line is set left to right in the English font, "c/o" as ©.
const setLine = (text, st) => {
  if (st.english) {
    return `\\vspace{${st.above}mm}\n{\\fontsize{${st.size}}{${st.size * 1.15}}\\selectfont\\textenglish{${text.replace(/c\/o/g, '\\textcopyright{}')}}}\\par`;
  }
  const font = st.bold ? `\\titlebold` : '\\hebrewfont';
  let body = `{${font}\\fontsize{${st.size}}{${st.size * 1.15}}\\selectfont ${toHebrewPunct(text)}}`;
  if (st.fit) body = `\\resizebox{${TITLE_WIDTH}}{!}{${body}}`;
  return `\\vspace{${st.above}mm}\n${body}\\par`;
};

const tex = `% Book title page - generated by build-title-page.mjs from title_page.txt.
\\documentclass[12pt]{article}
\\input{preamble-common.tex}
\\\pagestyle{empty}
\\setlength{\\parindent}{0pt}
\\newfontfamily\\titlebold{Magalith Tanach Pro}[Path = ../../vendor/fonts/, FakeBold = ${FAKE_BOLD}]
\\begin{document}
\\begin{hebrew}
\\centering
\\vspace*{${TOP_SKIP}}
${top.map((t, i) => setLine(t, TOP_STYLES[i])).join('\n')}
\\vfill
\\rule{${RULE_WIDTH}}{0.4pt}\\par
\\vspace{${RULE_BELOW}}
${bottom.map((t, i) => setLine(t, BOTTOM_STYLES[i])).join('\n')}
\\vspace{${BOTTOM_SKIP}}
\\end{hebrew}
\\end{document}
`;
fs.writeFileSync(path.join(HERE, 'title-page.tex'), tex, 'utf8');
console.log(`title page: ${top.length} lines + ${bottom.length} imprint lines -> title-page.tex`);

if (!process.argv.includes('--no-pdf')) {
  for (let i = 0; i < 2; i += 1) {
    const r = spawnSync('xelatex', ['-interaction=nonstopmode', 'title-page.tex'], { cwd: HERE, stdio: 'ignore' });
    if (r.status !== 0) throw new Error('xelatex failed - see title-page.log');
  }
  const log = fs.readFileSync(path.join(HERE, 'title-page.log'), 'utf8');
  const warnings = [
    ...[...log.matchAll(/^Missing character: (.*)$/gm)].map((m) => `missing glyph: ${m[1]}`),
    ...[...log.matchAll(/^Overfull \\hbox \((.*?)\) .*$/gm)].map((m) => `overfull line (${m[1]})`),
  ];
  const pages = Number(log.match(/Output written on .*?\((\d+) pages?/)?.[1] ?? 0);
  if (pages !== 1) warnings.push(`title-page.pdf has ${pages} pages - the page overflows`);
  console.log('wrote title-page.pdf');
  if (warnings.length) {
    console.log('Warnings:');
    warnings.forEach((w) => console.log(`  - ${w}`));
  }
}
